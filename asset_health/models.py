"""Pydantic contracts shared across the pipeline.

Every boundary between stages (simulator -> ingest -> detect -> RUL -> alerting -> report)
is expressed as one of these models. DataFrames are used *inside* a stage for vectorised
numerics; what crosses a stage boundary or is written to disk is validated here.
"""

from __future__ import annotations

import math
from datetime import datetime
from enum import StrEnum
from typing import Any, Literal

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    computed_field,
    field_validator,
    model_validator,
)

SYNTHETIC_NOTICE = (
    "SYNTHETIC DATA. Generated by asset_health.simulate from a seeded physical model. "
    "It is not measured data from any mine, plant or client, including any real operator."
)


_DERIVED_ORDERS = frozenset({"bpfo_order", "bpfi_order", "ftf_order", "bsf_order"})


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid")


class AssetType(StrEnum):
    CONVEYOR_IDLER = "conveyor_idler"
    CONVEYOR_PULLEY = "conveyor_pulley"
    PRIMARY_CRUSHER = "primary_crusher"
    SLURRY_PUMP = "slurry_pump"
    HAUL_TRUCK_ENGINE = "haul_truck_engine"


class FailureMode(StrEnum):
    """Ground-truth failure modes the simulator can inject."""

    BEARING_SPALL = "bearing_spall"
    IMPELLER_WEAR = "impeller_wear"
    LINER_WEAR = "liner_wear"
    OVERHEATING = "overheating"


class FaultHypothesis(StrEnum):
    """What the rule layer can name. Deliberately separate from ``FailureMode``: the detector
    never sees ground truth, and ``UNEXPLAINED`` is a legitimate answer."""

    BEARING_OUTER_RACE = "bearing_outer_race"
    BEARING_INNER_RACE = "bearing_inner_race"
    BEARING_GENERIC = "bearing_generic"
    IMPELLER_WEAR = "impeller_wear"
    LINER_WEAR = "liner_wear"
    OVERHEATING = "overheating"
    UNEXPLAINED = "unexplained_anomaly"


HYPOTHESIS_FAMILY: dict[FaultHypothesis, FailureMode | None] = {
    FaultHypothesis.BEARING_OUTER_RACE: FailureMode.BEARING_SPALL,
    FaultHypothesis.BEARING_INNER_RACE: FailureMode.BEARING_SPALL,
    FaultHypothesis.BEARING_GENERIC: FailureMode.BEARING_SPALL,
    FaultHypothesis.IMPELLER_WEAR: FailureMode.IMPELLER_WEAR,
    FaultHypothesis.LINER_WEAR: FailureMode.LINER_WEAR,
    FaultHypothesis.OVERHEATING: FailureMode.OVERHEATING,
    FaultHypothesis.UNEXPLAINED: None,
}


class Severity(StrEnum):
    NORMAL = "normal"
    WATCH = "watch"
    WARNING = "warning"
    URGENT = "urgent"
    CRITICAL = "critical"

    @property
    def rank(self) -> int:
        return _SEVERITY_ORDER[self]


_SEVERITY_ORDER = {
    Severity.NORMAL: 0,
    Severity.WATCH: 1,
    Severity.WARNING: 2,
    Severity.URGENT: 3,
    Severity.CRITICAL: 4,
}


class BearingGeometry(_Model):
    """Rolling-element bearing geometry. Defect frequencies are returned as *orders*
    (multiples of shaft frequency), which is how an order-tracked analyser reports them."""

    n_elements: int = Field(ge=4, le=40)
    ball_diameter_mm: float = Field(gt=0)
    pitch_diameter_mm: float = Field(gt=0)
    contact_angle_deg: float = Field(default=0.0, ge=0, lt=60)

    @model_validator(mode="before")
    @classmethod
    def _ignore_derived_orders(cls, data: Any) -> Any:
        """The defect orders are computed from the geometry and serialised with it; accept them
        back on load (a written manifest must be readable) but never trust them as inputs."""
        if isinstance(data, dict):
            return {k: v for k, v in data.items() if k not in _DERIVED_ORDERS}
        return data

    @model_validator(mode="after")
    def _check(self) -> BearingGeometry:
        if self.ball_diameter_mm >= self.pitch_diameter_mm:
            raise ValueError("ball diameter must be smaller than pitch diameter")
        return self

    @property
    def _ratio(self) -> float:
        return (
            self.ball_diameter_mm
            / self.pitch_diameter_mm
            * math.cos(math.radians(self.contact_angle_deg))
        )

    @computed_field  # type: ignore[prop-decorator]
    @property
    def bpfo_order(self) -> float:
        """Ball-pass frequency, outer race: (n/2) (1 - d/D cos a)."""
        return self.n_elements / 2.0 * (1.0 - self._ratio)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def bpfi_order(self) -> float:
        """Ball-pass frequency, inner race: (n/2) (1 + d/D cos a)."""
        return self.n_elements / 2.0 * (1.0 + self._ratio)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def ftf_order(self) -> float:
        """Fundamental train (cage) frequency: (1/2) (1 - d/D cos a)."""
        return 0.5 * (1.0 - self._ratio)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def bsf_order(self) -> float:
        """Ball spin frequency: (D/2d) (1 - (d/D cos a)^2)."""
        return self.pitch_diameter_mm / (2.0 * self.ball_diameter_mm) * (1.0 - self._ratio**2)


class AssetSpec(_Model):
    """Static description of one monitored asset (what a CMMS asset register would hold)."""

    asset_id: str
    asset_type: AssetType
    name: str
    area: str = "SYNTHETIC-PLANT"
    shaft_hz: float = Field(gt=0, description="Nominal monitored-shaft speed.")
    bearing: BearingGeometry
    proc_order: float | None = Field(
        default=None, description="Process line (vane pass / mesh / firing), in orders."
    )
    channels: tuple[str, ...]
    rated_power_kw: float | None = None
    baseline_scale: float = Field(default=1.0, gt=0, description="Asset-to-asset level factor.")
    component_age_days: float = Field(
        default=0.0,
        ge=0,
        description=(
            "Age of the monitored wear component at the start of the record, as a CMMS install "
            "date would give it. Used only by the age-based (calendar) replacement baseline."
        ),
    )

    @property
    def nominal_rpm(self) -> float:
        return self.shaft_hz * 60.0


class FailureEvent(_Model):
    """Ground truth: one injected degradation run ending in functional failure."""

    asset_id: str
    mode: FailureMode
    race: Literal["outer", "inner"] | None = None
    onset: datetime
    failure: datetime
    shape_k: float = Field(gt=0, description="Acceleration of the severity curve.")
    amplitude: float = Field(gt=0, description="Mode-specific signal strength multiplier.")
    downtime_hours: float = Field(gt=0)

    @model_validator(mode="after")
    def _order(self) -> FailureEvent:
        if self.failure <= self.onset:
            raise ValueError("failure must be after onset")
        return self

    @property
    def duration_days(self) -> float:
        return (self.failure - self.onset).total_seconds() / 86400.0


class MaintenanceEvent(_Model):
    """A CMMS record the pipeline is allowed to see (it is not ground truth).

    A tz-aware timestamp (a CMMS export with ``Z`` or ``+03:00``) is converted to naive UTC, the
    convention for every timestamp inside the package; a naive one is taken to be UTC already.
    """

    asset_id: str
    timestamp: datetime
    kind: Literal["planned_service", "repair"]
    note: str = ""

    @field_validator("timestamp", mode="after")
    @classmethod
    def _utc(cls, v: datetime) -> datetime:
        from asset_health.timeutil import to_utc_naive_datetime

        return to_utc_naive_datetime(v)


class DataFaultEvent(_Model):
    """Ground truth about an injected *data* fault (so the DQ checks can be scored)."""

    asset_id: str
    kind: Literal[
        "dropout",
        "stuck",
        "sentinel",
        "glitch",
        "comm_outage",
        "missing_row",
        "duplicate_row",
        "clock_drift",
    ]
    channel: str | None = None
    start: datetime
    end: datetime
    detail: str = ""


class GroundTruth(_Model):
    synthetic: Literal[True] = True
    notice: str = SYNTHETIC_NOTICE
    seed: int
    failures: list[FailureEvent]
    maintenance: list[MaintenanceEvent]
    data_faults: list[DataFaultEvent]


class FleetManifest(_Model):
    synthetic: Literal[True] = True
    notice: str = SYNTHETIC_NOTICE
    generator: str
    seed: int
    start: datetime
    days: int
    sample_interval_s: int
    baseline_days: int
    assets: list[AssetSpec]


# --------------------------------------------------------------------------- data quality


class DQStatus(StrEnum):
    PASS = "pass"
    WARN = "warn"
    FAIL = "fail"

    @property
    def rank(self) -> int:
        return {"pass": 0, "warn": 1, "fail": 2}[self.value]


class DQAction(StrEnum):
    NONE = "none"
    MASKED = "masked"  # offending values replaced by NaN, never fed to a detector
    RETIMED = "retimed"
    SORTED = "sorted"  # a newest-first export put back into time order
    RESAMPLED = "resampled"  # finer-than-configured cadence averaged onto the grid (opt-in)
    DEDUPLICATED = "deduplicated"
    CHANNEL_DISABLED = "channel_disabled"
    ASSET_BLOCKED = "asset_blocked"


class Segment(_Model):
    start: datetime
    end: datetime
    n_samples: int

    @property
    def hours(self) -> float:
        return (self.end - self.start).total_seconds() / 3600.0 + 1.0


class CheckResult(_Model):
    name: str
    status: DQStatus
    action: DQAction = DQAction.NONE
    message: str
    value: float | None = None


class ChannelDQ(_Model):
    channel: str
    n_samples: int
    n_missing: int
    n_out_of_range: int
    n_stuck: int
    n_spikes: int
    valid_fraction: float
    stuck_segments: list[Segment] = Field(default_factory=list)
    dropout_segments: list[Segment] = Field(default_factory=list)
    status: DQStatus
    usable: bool


class DataQualityReport(_Model):
    asset_id: str
    n_rows_in: int
    n_rows_grid: int
    start: datetime | None
    end: datetime | None
    overall: DQStatus
    asset_blocked: bool
    clock_drift_s_per_day: float
    n_duplicates: int
    n_backwards: int
    n_gap_samples: int
    longest_gap_hours: float
    checks: list[CheckResult]
    channels: dict[str, ChannelDQ]
    sensor_advisories: list[str] = Field(default_factory=list)
    erratic_segments: list[Segment] = Field(
        default_factory=list, description="Hours masked as a faulty vibration sensor."
    )

    @property
    def usable_fraction(self) -> float:
        if not self.channels:
            return 0.0
        return float(sum(c.valid_fraction for c in self.channels.values()) / len(self.channels))


# --------------------------------------------------------------------------- detection / RUL


class Evidence(_Model):
    """One feature that supports a finding. All numbers a work order may cite live here."""

    feature: str
    description: str
    observed: float
    expected: float
    z_score: float
    unit: str = ""


class Finding(_Model):
    timestamp: datetime
    hypothesis: FaultHypothesis
    strength: float
    rule: str
    evidence: list[Evidence]


class RULStatus(StrEnum):
    ESTIMATED = "estimated"
    INSUFFICIENT_TREND = "insufficient_trend"
    NOT_DEGRADING = "not_degrading"


class RULEstimate(_Model):
    """Remaining useful life. Always an interval; ``p50`` is a convenience, not the answer."""

    asset_id: str
    as_of: datetime
    status: RULStatus
    p10_days: float | None = None
    p50_days: float | None = None
    p90_days: float | None = None
    health_index: float | None = None
    failure_threshold: float | None = None
    method_trend_p50: float | None = None
    method_quantile_p50: float | None = None
    note: str = ""

    @model_validator(mode="after")
    def _interval(self) -> RULEstimate:
        if self.status == RULStatus.ESTIMATED:
            if None in (self.p10_days, self.p50_days, self.p90_days):
                raise ValueError("an ESTIMATED RUL must carry p10, p50 and p90")
            assert self.p10_days is not None and self.p50_days is not None
            assert self.p90_days is not None
            if not (self.p10_days <= self.p50_days <= self.p90_days):
                raise ValueError("RUL quantiles must be ordered p10 <= p50 <= p90")
        return self


# --------------------------------------------------------------------------- alerting


class WorkOrder(_Model):
    """Structured work-order recommendation. Machine-readable first; prose is derived."""

    synthetic: bool = True
    work_order_id: str
    asset_id: str
    asset_name: str
    asset_type: AssetType
    issued_at: datetime
    severity: Severity
    failure_mode_hypothesis: FaultHypothesis
    alternative_hypotheses: list[FaultHypothesis] = Field(default_factory=list)
    evidence: list[Evidence]
    recommended_action: str
    latest_safe_date: datetime | None
    rul: RULEstimate | None
    data_quality_note: str = ""
    narrative: str = ""
    narrative_source: Literal["template", "llm", "template_after_guardrail"] = "template"


class AlertEpisode(_Model):
    """One continuous alert on one asset. ``opened_at`` is when the debounce completed, i.e. the
    moment an operator would actually have been told, not when the score first rose."""

    asset_id: str
    opened_at: datetime
    closed_at: datetime | None
    peak_severity: Severity
    urgent_at: datetime | None = None
    closed_reason: str = ""
    hypothesis: FaultHypothesis = FaultHypothesis.UNEXPLAINED
    first_exceeded_at: datetime | None = None
    peak_score: float = 0.0
    threshold: float = 0.0
