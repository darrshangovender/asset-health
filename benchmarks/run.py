"""Regenerate every number in the README.

    python benchmarks/run.py            # full run: several minutes to an hour, depending on the CPU
    python benchmarks/run.py --quick    # smoke run on a handful of seeds; writes nothing

A full run
1. simulates the development, calibration and held-out seeds (SYNTHETIC) and caches the expensive
   pipeline stage under ``benchmarks/.cache``;
2. fits the RUL model on the development seeds and sets its conformal margin on the calibration
   seeds;
3. tunes the alert policy and both baselines on the development seeds;
4. scores everything on the held-out seeds and writes ``benchmarks/results.json`` and
   ``benchmarks/RESULTS.md``; the fitted RUL model is written to
   ``asset_health/data/rul_model.json`` (the file the CLI loads).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from asset_health.evaluate import BenchConfig, run_benchmark, save_results  # noqa: E402
from asset_health.evaluate.markdown import results_to_markdown  # noqa: E402

BEGIN, END = "<!-- RESULTS:BEGIN -->", "<!-- RESULTS:END -->"


def update_readme(path: Path, markdown: str) -> None:
    """Replace the block between the RESULTS markers, so README numbers cannot be hand-edited."""
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        return
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    block = "\n".join([BEGIN, markdown.strip(), END])
    path.write_text(head + block + tail, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--quick", action="store_true", help="few seeds, no ablations, writes nothing")
    ap.add_argument("--jobs", type=int, default=3, help="worker processes for the pipeline stage")
    ap.add_argument("--cache-dir", type=Path, default=HERE / ".cache")
    ap.add_argument("--out-dir", type=Path, default=HERE)
    ap.add_argument(
        "--model-out", type=Path, default=HERE.parent / "asset_health" / "data" / "rul_model.json"
    )
    ap.add_argument("--no-ablations", action="store_true")
    ap.add_argument(
        "--readme",
        type=Path,
        default=HERE.parent / "README.md",
        help="README whose RESULTS block is refreshed from results.json (full runs only)",
    )
    args = ap.parse_args(argv)

    bc = BenchConfig()
    if args.quick:
        bc = bc.quick()
    if args.no_ablations:
        bc.ablations = False
    results, model = run_benchmark(
        bc, cache_dir=args.cache_dir, n_jobs=args.jobs, progress=lambda s: print(s, flush=True)
    )
    md = results_to_markdown(results)
    print("\n" + md)
    if args.quick:
        print(f"(quick run: {results['runtime_s']:.0f}s, nothing written)")
        return 0
    args.out_dir.mkdir(parents=True, exist_ok=True)
    save_results(results, args.out_dir / "results.json")
    (args.out_dir / "RESULTS.md").write_text(
        "# Benchmark results (SYNTHETIC data)\n\nGenerated by `python benchmarks/run.py`.\n\n" + md,
        encoding="utf-8",
    )
    update_readme(args.readme, md)
    args.model_out.parent.mkdir(parents=True, exist_ok=True)
    model.save(args.model_out)
    print(
        f"wrote {args.out_dir / 'results.json'}, RESULTS.md and {args.model_out} "
        f"({results['runtime_s']:.0f}s)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
